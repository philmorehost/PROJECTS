#!/usr/bin/env python3
"""Capture the pre-migration page bodies that plate_migration_test.php compares against.

Run from the repository root after the pages have been migrated:

    python3 VTU/tests/plate_capture.py

The bodies are written to VTU/tests/plate_bodies.php as nowdoc strings, so the test
needs neither git nor a shell. Regenerate whenever a page is migrated by hand.
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EDITIONS = ('DGV7.0-SAAS', 'DGV7.0-NON-SAAS')
BUNDLE = '    <script src="../assets-2/vendor/bootstrap/js/bootstrap.bundle.min.js"></script>\n'
MARK = 'PLATEBODY'


def migrated_pages():
    pages = []
    for ed in EDITIONS:
        d = os.path.join(ROOT, 'VTU', ed, 'web')
        for name in sorted(os.listdir(d)):
            if name.endswith('.php') and name != 'Dashboard.php':
                pages.append('VTU/' + ed + '/web/' + name)
    return pages


def body_of(src):
    start = src.find('</div>', src.find('<div class="pagetitle'))
    if start == -1:
        return None
    end = src.find('<?php include("../func/bc-footer.php"); ?>')
    if end == -1:
        end = src.find('include("../func/bc-footer.php");')
    if end == -1:
        return None
    return src[start + 6:end]


def main():
    out = path = None
    parts = [
        "<?php\n",
        "// Pre-migration page bodies, captured from the revision the shell replaced.\n",
        "// Generated by VTU/tests/plate_capture.py — do not edit by hand.\n",
        "// See plate_migration_test.php.\n",
        "return array(\n",
    ]
    n = 0
    ref = 'HEAD'
    if '--from' in sys.argv:
        ref = sys.argv[sys.argv.index('--from') + 1]
    for rel in migrated_pages():
        path = os.path.join(ROOT, rel)
        cur = open(path, errors='replace').read()
        if 'bc_app_head(' not in cur:
            continue
        old = subprocess.run(['git', '-C', ROOT, 'show', ref + ':' + rel],
                             capture_output=True, text=True).stdout
        body = body_of(old)
        if body is None:
            continue
        body = body.replace(BUNDLE, '').rstrip(' \t')
        if MARK in body:
            print('SKIP %s (body contains the nowdoc marker)' % rel, file=sys.stderr)
            continue
        parts.append('    ' + json.dumps(rel) + " => <<<'%s'\n%s\n%s,\n" % (MARK, body, MARK))
        n += 1
    parts.append(");\n")
    if n == 0:
        print('refusing to write: no bodies captured from %s '
              '(run this before migrating, or pass --from <pre-migration sha>)' % ref,
              file=sys.stderr)
        return 1
    out = os.path.join(ROOT, 'VTU', 'tests', 'plate_bodies.php')
    open(out, 'w').write(''.join(parts))
    print('captured %d bodies -> %s' % (n, out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
