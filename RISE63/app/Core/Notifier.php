<?php
declare(strict_types=1);

namespace RISE63\Core;

/**
 * Transactional notification queue.
 *
 * Mail is never sent inside a web request: rows land in notification_outbox and the CLI
 * worker (bin/mail-worker.php) delivers them with retry and backoff. Passwords and PINs are
 * never placed in a queued message; the welcome mail explains how to obtain credentials
 * through a trusted channel instead.
 */
final class Notifier
{
    /** @param array<string, string> $facts */
    public static function securityAlert(string $headline, array $facts): void
    {
        $recipient = (string) Settings::get('notification_email', '');
        if ($recipient === '') {
            return;
        }
        $rows = '';
        foreach ($facts as $label => $value) {
            $rows .= '<tr><th style="text-align:left;padding:6px 12px 6px 0;color:#475569;font-weight:600">'
                . \RISE63\e($label) . '</th><td style="padding:6px 0">' . \RISE63\e($value) . '</td></tr>';
        }
        $body = '<h2 style="margin:0 0 8px;font-size:20px">' . \RISE63\e($headline) . '</h2>'
            . '<p style="margin:0 0 16px;color:#334155">This alert was generated by the RISE 63 security engine.</p>'
            . '<table style="border-collapse:collapse;font-size:15px">' . $rows . '</table>'
            . '<p style="margin:18px 0 0;color:#64748b;font-size:13px">Open Security → Security log for the full timeline. '
            . 'If this was not expected, suspend the account and change the notification address.</p>';
        self::queue($recipient, 'RISE 63 security: ' . $headline, $body, 'security');
    }

    /** @param array<string, mixed> $user */
    public static function adminLoginAlert(array $user, string $ip, string $country): void
    {
        $recipient = (string) Settings::get('notification_email', '');
        if ($recipient === '') {
            return;
        }
        $body = '<h2 style="margin:0 0 8px;font-size:20px">Sign-in from an unrecognised network</h2>'
            . '<p style="margin:0 0 14px;color:#334155">' . \RISE63\e((string) $user['full_name'])
            . ' signed in and this address is not yet recognised by the platform.</p>'
            . '<ul style="font-size:15px;color:#334155"><li>Account: ' . \RISE63\e((string) $user['email']) . '</li>'
            . '<li>Role: ' . \RISE63\e(Auth::ROLES[(string) $user['role']] ?? (string) $user['role']) . '</li>'
            . '<li>IP address: ' . \RISE63\e($ip) . '</li><li>Country: ' . \RISE63\e($country) . '</li>'
            . '<li>Time (UTC): ' . \RISE63\e(gmdate('Y-m-d H:i')) . '</li></ul>';
        self::queue($recipient, 'RISE 63: sign-in from a new network', $body, 'security');
    }

    /** @param array<string, mixed> $user */
    public static function welcome(array $user): void
    {
        $body = self::wrap(
            'Welcome to RISE 63',
            '<p>Hello ' . \RISE63\e((string) $user['full_name']) . ',</p>'
            . '<p>Your RISE 63 profile is ready. Sign in with the e-mail address below and the temporary password '
            . 'your parish representative gave you, then choose your own password immediately.</p>'
            . '<p><strong>E-mail:</strong> ' . \RISE63\e((string) $user['email']) . '</p>'
            . '<p>For your protection this message never contains a password or transaction PIN. '
            . 'If you did not expect this account, contact the province office.</p>'
        );
        self::queue((string) $user['email'], 'Your RISE 63 account is ready', $body, 'transactional');
    }

    /** @param array<string, mixed> $application */
    public static function applicationStatus(array $application, string $toStatus, string $note = ''): void
    {
        $user = Database::one('SELECT email, full_name FROM users WHERE id = ?', [(int) $application['user_id']]);
        if ($user === null) {
            return;
        }
        $program = Program::label((string) $application['program_type']);
        $steps   = Program::tracker((string) $application['program_type'], $toStatus);
        $body    = self::wrap(
            $program . ' update',
            '<p>Hello ' . \RISE63\e((string) $user['full_name']) . ',</p>'
            . '<p>Your <strong>' . \RISE63\e($program) . '</strong> application is now <strong>'
            . \RISE63\e(Program::statusLabel($toStatus)) . '</strong>.</p>'
            . $steps
            . ($note !== '' ? '<p><strong>Note from the review team:</strong> ' . \RISE63\e($note) . '</p>' : '')
        );
        self::queue((string) $user['email'], $program . ': ' . Program::statusLabel($toStatus), $body, 'transactional');
    }

    /** @param array<string, mixed> $remittance */
    public static function disbursement(array $remittance, array $application): void
    {
        $user = Database::one('SELECT email, full_name FROM users WHERE id = ?', [(int) $application['user_id']]);
        if ($user === null) {
            return;
        }
        $amount = Money::fromDecimal($remittance['amount']);
        $body   = self::wrap(
            'Disbursement recorded',
            '<p>Hello ' . \RISE63\e((string) $user['full_name']) . ',</p>'
            . '<p>A disbursement of <strong>' . \RISE63\e($amount->format()) . '</strong> has been recorded for your '
            . \RISE63\e(Program::label((string) $application['program_type'])) . ' application.</p>'
            . '<ul><li>Reference: ' . \RISE63\e((string) $remittance['payment_reference']) . '</li>'
            . '<li>Payee: ' . \RISE63\e((string) $remittance['payee_name']) . '</li>'
            . '<li>Bank: ' . \RISE63\e((string) $remittance['bank_name']) . '</li></ul>'
            . '<p>Contact the province treasury if these details are not correct.</p>'
        );
        self::queue((string) $user['email'], 'RISE 63 disbursement: ' . $amount->format(), $body, 'transactional');
    }

    /**
     * A security-relevant change to the account itself. Deliberately does not read the member's
     * notification preference: these messages are the reason the preference exists.
     */
    public static function securityNotice(array $user, string $subject, string $headline, string $bodyHtml): void
    {
        self::queue((string) $user['email'], 'RISE 63: ' . $subject, self::wrap($headline, $bodyHtml), 'security');
    }

    public static function preferenceChanged(array $user, string $preference, bool $enabled): void
    {
        $body = self::wrap(
            'Notification preference changed',
            '<p>The preference <strong>' . \RISE63\e($preference) . '</strong> is now <strong>'
            . ($enabled ? 'enabled' : 'disabled') . '</strong> on your RISE 63 profile.</p>'
            . '<p>If you did not make this change, sign in and revoke your other devices.</p>'
        );
        self::queue((string) $user['email'], 'RISE 63: notification preference updated', $body, 'transactional');
    }

    public static function queue(string $recipient, string $subject, string $html, string $category = 'transactional'): void
    {
        $recipient = strtolower(trim($recipient));
        if (!filter_var($recipient, FILTER_VALIDATE_EMAIL) || strlen($recipient) > 150) {
            return;
        }
        $text = self::toText($html);
        Database::run(
            'INSERT INTO notification_outbox (recipient, subject, body_html, body_text, category, available_at) VALUES (?,?,?,?,?,UTC_TIMESTAMP())',
            [$recipient, mb_substr($subject, 0, 200), $html, $text, $category]
        );
    }

    public static function wrap(string $heading, string $content): string
    {
        $site = \RISE63\e(\RISE63\site_title());
        return '<div style="font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;background:#f1f5f9;padding:24px">'
            . '<div style="max-width:560px;margin:0 auto;background:#ffffff;border-radius:14px;padding:28px;color:#0f172a">'
            . '<p style="margin:0 0 6px;font-size:12px;letter-spacing:2px;color:#2563eb;font-weight:700">' . strtoupper($site) . '</p>'
            . '<h2 style="margin:0 0 16px;font-size:21px">' . \RISE63\e($heading) . '</h2>'
            . '<div style="font-size:16px;line-height:1.65">' . $content . '</div>'
            . '<hr style="border:0;border-top:1px solid #e2e8f0;margin:24px 0 12px">'
            . '<p style="margin:0;font-size:12px;color:#64748b">' . $site . ' · RCCG Lagos Province 63</p>'
            . '</div></div>';
    }

    public static function toText(string $html): string
    {
        $text = preg_replace('#<(script|style)[^>]*>.*?</\1>#is', '', $html) ?? '';
        $text = preg_replace('#<br\s*/?>#i', "\n", $text) ?? '';
        $text = preg_replace('#</(p|div|h1|h2|h3|li|tr)>#i', "\n", $text) ?? '';
        $text = preg_replace('#<li[^>]*>#i', ' • ', $text) ?? '';
        $text = strip_tags($text);
        $text = html_entity_decode($text, ENT_QUOTES | ENT_HTML5, 'UTF-8');
        $text = preg_replace('/[ \t]+/', ' ', $text) ?? '';
        $text = preg_replace('/\n{3,}/', "\n\n", $text) ?? '';
        return trim($text);
    }
}
