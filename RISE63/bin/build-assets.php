<?php
declare(strict_types=1);

/**
 * Asset builder. Run after editing anything in public/assets/:
 *
 *   php bin/build-assets.php
 *
 * It writes a content-hashed copy of every source asset, a manifest the view helper reads
 * (public/assets/manifest.php), and the service-worker shell list (public/assets/sw-assets.js).
 * Fingerprinted files are safe to cache immutably for a year; the unhashed sources stay in the
 * tree so the app still works before a build has been run.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$dir = dirname(__DIR__) . '/public/assets';
// The public site's two files are separate sources, built the same way: the landing page is a
// different document with a different stylesheet, and bundling it into app.css would ship the whole
// application's CSS to every anonymous visitor.
$sources = ['app.css', 'app.js', 'security.js', 'site.css', 'site.js'];

$manifest = [];
$written  = [];
$sheet    = [];

foreach (scandir($dir) ?: [] as $existing) {
    if (preg_match('/^(.+)\.[0-9a-f]{8}\.(css|js)$/', $existing, $m)) {
        @unlink($dir . '/' . $existing); // Remove stale builds first.
    }
}

foreach ($sources as $source) {
    $path = $dir . '/' . $source;
    if (!is_file($path)) {
        fwrite(STDERR, "missing asset: {$source}\n");
        continue;
    }
    $contents = (string) file_get_contents($path);
    $hash     = substr(hash('sha256', $contents), 0, 8);
    $info     = pathinfo($source);
    $target   = $info['filename'] . '.' . $hash . '.' . $info['extension'];
    if (file_put_contents($dir . '/' . $target, $contents) === false) {
        fwrite(STDERR, "could not write {$target}\n");
        exit(1);
    }
    $manifest[$source] = $target;
    $written[]         = $target;
}

if (file_put_contents($dir . '/manifest.php', "<?php\n// Generated by bin/build-assets.php — do not edit.\nreturn " . var_export($manifest, true) . ";\n", LOCK_EX) === false) {
    fwrite(STDERR, "could not write manifest.php\n");
    exit(1);
}

$sheet = [
    './manifest.webmanifest',
    './favicon.svg',
    './public/icons/icon-192.png',
    './public/icons/icon-512.png',
];
foreach ($manifest as $source => $hashed) {
    $sheet[] = './public/assets/' . $hashed;
}
file_put_contents(
    $dir . '/sw-assets.js',
    "/* Generated by bin/build-assets.php — do not edit. */\n"
    . "self.RISE63_SHELL = " . json_encode($sheet, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . ";\n"
    // The release id is what the service worker folds into its cache name, so a deploy that
    // changes the app but not the asset list still invalidates the cached shell.
    . "self.RISE63_RELEASE = " . json_encode(\RISE63\VERSION . '-' . substr(hash('sha256', implode(',', array_keys($manifest)) . implode('', $written)), 0, 8)) . ";\n",
    LOCK_EX
);

fwrite(STDOUT, "Built " . count($written) . " asset(s):\n  " . implode("\n  ", $written) . "\n");
